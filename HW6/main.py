num1 = float(input('Введите первое число: '))
num2 = float(input('Введите второе число: '))
operator = input("Выберите оператор (+,-,*,/): ")
if operator == '+':
    print(num1 + num2)
elif operator == '-':
    print(num1 - num2)
elif operator == '*':
    print(num1 * num2)
elif operator == '/':
    print(num1 / num2)
